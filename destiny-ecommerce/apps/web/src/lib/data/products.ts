export const getProductsByCategory = (categorySlug: string) =>
  products.filter(p => p.category.slug === categorySlug)

export const getFeaturedProducts = () =>
  products.filter(p => p.isFeatured).slice(0, 8)

export const getNewArrivals = () =>
  products.filter(p => p.isNew).slice(0, 8)

export const getBestSellers = () =>
  products.filter(p => p.isBestSeller).slice(0, 8)

export const getFlashSaleProducts = () =>
  products.filter(p => p.isFlashSale).slice(0, 6)

export const getProductById = (id: string) =>
  products.find(p => p.id === id)

export const getProductBySlug = (slug: string) =>
  products.find(p => p.slug === slug)

export const searchProducts = (query: string) =>
  products.filter(p =>
    p.name.toLowerCase().includes(query.toLowerCase()) ||
    p.description.toLowerCase().includes(query.toLowerCase()) ||
    p.tags.some(t => t.toLowerCase().includes(query.toLowerCase()))
  )

export const formatCFA = (price: number): string =>
  new Intl.NumberFormat('fr-CM', { style: 'currency', currency: 'XAF', maximumFractionDigits: 0 })
    .format(price)
    .replace('XAF', 'FCFA')
